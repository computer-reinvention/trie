def test_install_skips_pointer_when_agent_files_absent(tmp_path: Path):
    """If neither AGENTS.md nor CLAUDE.md exists, `install` doesn't create
    them. We treat those filenames as user-authored conventions; conjuring
    them out of thin air implies an opinion we don't have.

    The TRIE.md write still happens — that's the trie-owned artefact.
    """
    plan = install(project_root=tmp_path, print_only=False, dry_run=False)
    assert not (tmp_path / "AGENTS.md").exists()
    assert not (tmp_path / "CLAUDE.md").exists()
    # Only TRIE.md is in the plan; no pointer-line results were emitted.
    assert {r.target for r in plan.results} == {TRIE_DOC_FILENAME}


def test_install_appends_pointer_to_existing_agents_md(tmp_path: Path):
    """When AGENTS.md is present, the pointer block lands at the end with
    a blank-line separator from whatever the user had above."""
    (tmp_path / "AGENTS.md").write_text("# AGENTS.md\n\nOur conventions.\n")
    install(project_root=tmp_path, print_only=False, dry_run=False)
    content = (tmp_path / "AGENTS.md").read_text(encoding="utf-8")
    # User's content is preserved verbatim.
    assert "Our conventions." in content
    # Pointer block was added.
    assert POINTER_MARKER in content
    assert POINTER_END_MARKER in content
    assert "TRIE.md" in content
    # The pointer points at TRIE.md, not at some external URL — agents on
    # offline boxes still resolve the link.
    assert POINTER_LINE in content


def test_install_appends_pointer_to_existing_claude_md(tmp_path: Path):
    """CLAUDE.md gets the same treatment as AGENTS.md. Both conventions
    are equally supported; whichever the user maintains is the one that
    becomes discoverable."""
    (tmp_path / "CLAUDE.md").write_text("# Claude conventions\n")
    install(project_root=tmp_path, print_only=False, dry_run=False)
    content = (tmp_path / "CLAUDE.md").read_text(encoding="utf-8")
    assert POINTER_MARKER in content
    assert "TRIE.md" in content


def test_install_handles_both_agents_and_claude_files(tmp_path: Path):
    """Most projects pick one convention, but a few keep both (or
    symlink). Each file gets its own pointer block; the plan reports
    both writes."""
    (tmp_path / "AGENTS.md").write_text("# AGENTS.md\n")
    (tmp_path / "CLAUDE.md").write_text("# CLAUDE.md\n")
    plan = install(project_root=tmp_path, print_only=False, dry_run=False)
    targets = {r.target for r in plan.results}
    assert "AGENTS.md" in targets
    assert "CLAUDE.md" in targets
    # Both files now have a pointer block.
    for filename in ("AGENTS.md", "CLAUDE.md"):
        assert POINTER_MARKER in (tmp_path / filename).read_text(encoding="utf-8")


def test_install_pointer_is_idempotent(tmp_path: Path):
    """Two installs in a row: the second's pointer result is `skipped`
    because the marker block is already present with the same body."""
    (tmp_path / "AGENTS.md").write_text("# AGENTS.md\n\nOriginal content.\n")
    install(project_root=tmp_path, print_only=False, dry_run=False)
    second = install(project_root=tmp_path, print_only=False, dry_run=False)
    agents_result = next(r for r in second.results if r.target == "AGENTS.md")
    assert agents_result.action == "skipped"


def test_install_refreshes_stale_pointer_block_in_place(tmp_path: Path):
    """If an older trie version wrote a slightly different pointer line,
    a new install must replace ONLY the block between markers, leaving
    everything else untouched."""
    stale_block = (
        f"{POINTER_MARKER}\nOLD pointer line that no longer matches.\n{POINTER_END_MARKER}\n"
    )
    user_content = "# AGENTS.md\n\nUser content above.\n"
    user_below = "\nUser content below the block.\n"
    (tmp_path / "AGENTS.md").write_text(user_content + "\n" + stale_block + user_below)

    install(project_root=tmp_path, print_only=False, dry_run=False)

    final = (tmp_path / "AGENTS.md").read_text(encoding="utf-8")
    # User content on both sides preserved.
    assert "User content above." in final
    assert "User content below the block." in final
    # Old pointer is gone, new one is there.
    assert "OLD pointer line that no longer matches." not in final
    assert POINTER_LINE in final


# ---------------------------------------------------------------------------
# Preview / dry-run: never write
# ---------------------------------------------------------------------------


def test_print_only_does_not_write_anything(tmp_path: Path):
    """`--print-only` is for inspecting the plan; nothing lands on disk."""
    (tmp_path / "AGENTS.md").write_text("# AGENTS.md\n")
    plan = install(project_root=tmp_path, print_only=True, dry_run=False)
    # TRIE.md not created.
    assert not (tmp_path / TRIE_DOC_FILENAME).exists()
    # AGENTS.md unchanged.
    assert (tmp_path / "AGENTS.md").read_text(encoding="utf-8") == "# AGENTS.md\n"
    # The plan still describes what would happen.
    for r in plan.results:
        assert r.action == "preview"


def test_dry_run_does_not_write_when_file_already_correct(tmp_path: Path):
    """`--dry-run` short-circuits at the "would write" step. If the file
    on disk matches what we'd write, we still report `skipped` (no work
    to do); if it doesn't match, we return `preview` without writing."""
    install(project_root=tmp_path, print_only=False, dry_run=False)
    second = install(project_root=tmp_path, print_only=False, dry_run=True)
    trie_result = next(r for r in second.results if r.target == TRIE_DOC_FILENAME)
    # Already up to date, so even dry-run reports `skipped` — the comparison
    # happens before the dry-run early-return.
    assert trie_result.action == "skipped"


