def test_splice_appends_when_marker_absent(tmp_path: Path):
    """Direct test of the splice routine: no marker → append at end with
    a blank-line separator. Belt-and-braces against future regressions in
    the higher-level write path."""
    original = "# Header\n\nSome content.\n"
    result = _splice_pointer_block(original)
    assert result.startswith("# Header\n\nSome content.\n")
    assert POINTER_MARKER in result
    assert POINTER_END_MARKER in result
    # No stray double-blank-lines that would accumulate on repeated calls.
    assert "\n\n\n\n" not in result


def test_splice_replaces_when_marker_present():
    """When the marker block exists, splice rewrites between markers only
    and never duplicates."""
    original = f"# Header\n\n{POINTER_MARKER}\nOLD body.\n{POINTER_END_MARKER}\n\nFooter content.\n"
    result = _splice_pointer_block(original)
    assert "OLD body." not in result
    # Only one marker pair survives — no duplication on repeated rewrites.
    assert result.count(POINTER_MARKER) == 1
    assert result.count(POINTER_END_MARKER) == 1
    # Surrounding content is preserved.
    assert "# Header" in result
    assert "Footer content." in result


def test_splice_handles_empty_input():
    """Edge case: an empty file gets only the pointer block, no leading
    blank line to clean up."""
    result = _splice_pointer_block("")
    assert result.startswith(POINTER_MARKER)


