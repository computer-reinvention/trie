"""Tests for `trie.docs_install`: project-local agent documentation install.

Contract under test:

  - `install(project_root=...)` always writes `TRIE.md` at the project
    root. The bundled body comes from `trie/data/TRIE.md`; the file gets
    a generated-file notice prepended so a curious reader knows where it
    came from.
  - When `AGENTS.md` or `CLAUDE.md` already exist at the project root,
    each receives a marker-fenced pointer block. Missing files are NOT
    materialised — that's user-owned territory.
  - Idempotency: running twice in a row produces `skipped` results when
    the on-disk content already matches the canonical write.
  - The pointer block has stable markers so the next run finds and
    refreshes only the block, leaving the rest of the file alone.
  - `--print-only` / `--dry-run` never write files (still returns
    `preview` results with full would-be contents).
"""

from __future__ import annotations

from pathlib import Path

from trie.docs_install import (
    AGENT_DOC_FILES,
    POINTER_END_MARKER,
    POINTER_LINE,
    POINTER_MARKER,
    TRIE_DOC_FILENAME,
    _splice_pointer_block,
    install,
)

# ---------------------------------------------------------------------------
# TRIE.md materialisation
# ---------------------------------------------------------------------------


def test_install_creates_trie_md_at_project_root(tmp_path: Path):
    """The headline contract: `install` writes a project-local TRIE.md.

    The body must be non-empty (we've actually loaded the bundled doc, not
    just touched the file) and must carry the generated-file notice so a
    reader can identify its provenance at a glance.
    """
    plan = install(project_root=tmp_path, print_only=False, dry_run=False)
    trie_md = tmp_path / TRIE_DOC_FILENAME
    assert trie_md.exists()
    body = trie_md.read_text(encoding="utf-8")
    assert "Generated by `trie setup`" in body
    # Sanity check we actually loaded the bundled body — the doc opens
    # with the title of the guide.
    assert "Using trie" in body
    # The plan reflects the write.
    trie_result = next(r for r in plan.results if r.target == TRIE_DOC_FILENAME)
    assert trie_result.action == "created"


def test_install_trie_md_is_idempotent_on_identical_content(tmp_path: Path):
    """A second `install` against the same project root sees `skipped`.

    This is what makes `trie setup` safe to run on every checkout: the
    work is bounded by what actually changed.
    """
    install(project_root=tmp_path, print_only=False, dry_run=False)
    second = install(project_root=tmp_path, print_only=False, dry_run=False)
    trie_result = next(r for r in second.results if r.target == TRIE_DOC_FILENAME)
    assert trie_result.action == "skipped"
    assert "up to date" in trie_result.detail.lower()


def test_install_trie_md_updates_on_drift(tmp_path: Path):
    """If something (or someone) modified TRIE.md since the last install,
    `install` rewrites it. The contract is "TRIE.md mirrors the bundled
    doc"; hand-edits don't survive — that's why the generated notice tells
    the user so."""
    install(project_root=tmp_path, print_only=False, dry_run=False)
    (tmp_path / TRIE_DOC_FILENAME).write_text("garbage that doesn't match\n")
    second = install(project_root=tmp_path, print_only=False, dry_run=False)
    trie_result = next(r for r in second.results if r.target == TRIE_DOC_FILENAME)
    assert trie_result.action == "updated"
    # The on-disk content is back to the bundled body.
    assert "Using trie" in (tmp_path / TRIE_DOC_FILENAME).read_text(encoding="utf-8")


