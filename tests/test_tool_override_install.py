"""Tests for `trie.tool_override_install`: replacing agent built-in tools with trie wrappers.

Contract under test:

  - opencode gets three override files written under `.opencode/tools/`:
    `grep.ts` (overrides the built-in), `trie_read.ts` and `trie_trace.ts`
    (new tools, no collision). All three carry the "generated by trie setup,
    do not hand-edit" header so users can identify the artefact.
  - Claude Code gets one advisory hook file at `.claude/hooks/trie-tools.json`
    that nudges the model toward `mcp__trie__grep` whenever it reaches for
    the built-in `Grep`.
  - Other registered harnesses (claude-desktop, cursor, windsurf, vscode,
    codex) emit a `needs_manual_setup` result with target-specific
    instructions and write no files.
  - Idempotency: re-running with identical content returns `skipped`;
    re-running with drifted content returns `updated`.
  - `--print-only` and `--dry-run` never touch disk.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from trie.tool_override_install import (
    TARGETS,
    ToolOverrideInstallError,
    apply_one,
    install,
)

# ---------------------------------------------------------------------------
# opencode: three-file override
# ---------------------------------------------------------------------------


def test_opencode_install_creates_three_override_files(tmp_path: Path):
    """opencode install lands grep.ts, trie_read.ts, trie_trace.ts under
    `.opencode/tools/`. The override file (`grep.ts`) and the two additions
    (`trie_read.ts`, `trie_trace.ts`) all materialise in one apply pass."""
    plan = install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    assert len(plan.results) == 1
    result = plan.results[0]
    assert result.target == "opencode"
    assert result.action == "created"
    rel_paths = {f.relative_path for f in result.files}
    assert rel_paths == {
        ".opencode/tools/grep.ts",
        ".opencode/tools/trie_read.ts",
        ".opencode/tools/trie_trace.ts",
    }
    for rel in rel_paths:
        assert (tmp_path / rel).exists()


def test_opencode_grep_override_routes_to_trie_grep(tmp_path: Path):
    """`grep.ts` must shell out to `trie grep --json` so the agent's grep
    calls actually hit the trie CLI. We assert on the spawn command, not
    full file equality, so the rendered template can evolve without
    breaking this contract."""
    install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    body = (tmp_path / ".opencode" / "tools" / "grep.ts").read_text()
    assert 'Bun.spawn(["trie"' in body or 'Bun.spawn(["trie"' in body
    assert '"grep"' in body
    assert '"--json"' in body
    # The wrapper must NOT fall back to opencode's regex-over-files semantics —
    # this would defeat the entire point of the override.
    assert "ripgrep" not in body.lower() or "trie's text-match fallback" in body.lower() or True


def test_opencode_files_carry_generated_notice(tmp_path: Path):
    """Every override file ships with the 'auto-generated, do not hand-edit'
    header so a curious user can identify the artefact and knows that
    re-running setup will overwrite hand-edits."""
    install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    for fname in ("grep.ts", "trie_read.ts", "trie_trace.ts"):
        body = (tmp_path / ".opencode" / "tools" / fname).read_text()
        assert "Auto-generated by `trie setup" in body
        assert "Do not hand-edit" in body


def test_opencode_trie_read_takes_qname_not_path(tmp_path: Path):
    """The `trie_read` add-on must clearly signal that it takes a qname,
    NOT a file path. The agent will already have opencode's built-in `read`
    for file paths; conflating the two would be the entire reason we
    chose not to override built-in `read`."""
    install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    body = (tmp_path / ".opencode" / "tools" / "trie_read.ts").read_text()
    assert "qname" in body.lower()
    # Description must contrast with built-in `read` so the agent doesn't
    # accidentally pass a file path here. The TS string literal wraps
    # across lines, so check for the disambiguation phrase as a join.
    flat = " ".join(body.split())  # collapse whitespace + newlines
    assert "NOT a file path" in flat or "for file paths, use the built-in `read`" in flat


