def test_claude_code_install_creates_advisory_hook(tmp_path: Path):
    """Claude Code's only available steering mechanism is a `PreToolUse`
    hook. The install writes one JSON file under `.claude/hooks/` that
    matches on the built-in `Grep` tool and emits a system message
    pointing at `mcp__trie__grep`."""
    plan = install(
        target_names=["claude-code"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    result = plan.results[0]
    assert result.action == "created"
    hook_path = tmp_path / ".claude" / "hooks" / "trie-tools.json"
    assert hook_path.exists()
    body = json.loads(hook_path.read_text())
    # The hook is structured per Claude Code's documented schema.
    assert "hooks" in body
    pre_tool_use = body["hooks"]["PreToolUse"]
    assert isinstance(pre_tool_use, list) and len(pre_tool_use) == 1
    matcher_block = pre_tool_use[0]
    # It targets the built-in Grep tool by name (regex-free string match).
    assert matcher_block["matcher"] == "Grep"
    # And the handler runs a shell command that emits a systemMessage —
    # the only documented way to inject text Claude sees on next turn.
    cmd = matcher_block["hooks"][0]["command"]
    assert "systemMessage" in cmd
    assert "mcp__trie__grep" in cmd


def test_claude_code_hook_does_not_deny_grep(tmp_path: Path):
    """Per design: Claude Code's hook is advisory only, not blocking. The
    rendered command must NOT produce a `permissionDecision: deny` because
    we don't want to break legitimate Grep usage on non-source files. If a
    future change accidentally turns this into a deny rule, the test
    fails loudly."""
    install(
        target_names=["claude-code"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    body = (tmp_path / ".claude" / "hooks" / "trie-tools.json").read_text()
    assert "permissionDecision" not in body
    assert '"deny"' not in body


