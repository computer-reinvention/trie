def test_print_only_does_not_write_anything(tmp_path: Path):
    """`--print-only` is for inspecting the plan; nothing lands on disk.
    Each file-to-write result is `preview` and carries the would-be
    contents in `detail` for the renderer to print. Obsolete-file
    cleanups for files that don't exist report `skipped` regardless of
    --print-only because there's nothing to preview removing."""
    plan = install(
        target_names=["opencode"],
        print_only=True,
        dry_run=False,
        project_root=tmp_path,
    )
    result = plan.results[0]
    assert result.action == "preview"
    assert not (tmp_path / ".opencode").exists()
    # The new-file write results are all `preview` with rendered contents
    # in `detail`. Cleanup-of-non-existent results are `skipped` (no body
    # to render). Filter by description to separate the two cohorts.
    write_results = [f for f in result.files if "obsolete" not in f.description.lower()]
    for f in write_results:
        assert f.action == "preview"
        assert f.detail  # the rendered file body


def test_dry_run_does_not_write_when_file_already_correct(tmp_path: Path):
    """`--dry-run` short-circuits before writing. If the file on disk
    matches what we'd write, we still report `skipped` (no work to do);
    if it doesn't match, we return `preview` without writing.

    This mirrors the existing hook-install + docs-install dry-run
    contracts so all three subcommands feel consistent."""
    install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    second = install(
        target_names=["opencode"],
        print_only=False,
        dry_run=True,
        project_root=tmp_path,
    )
    # Already up to date, so even dry-run reports `skipped`.
    assert second.results[0].action == "skipped"


