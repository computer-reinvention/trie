def test_opencode_install_is_idempotent_on_identical_content(tmp_path: Path):
    """Running install twice with no changes: the second run reports
    `skipped` for every file. This is what makes `trie setup` safe to run
    on every checkout."""
    install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    second = install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    result = second.results[0]
    assert result.action == "skipped"
    # Write results report "same contents"; cleanup results for absent
    # obsolete files report "nothing to clean up". Both are `skipped`,
    # but the detail strings differ — filter by description before
    # asserting on detail.
    for f in result.files:
        assert f.action == "skipped"
        if "obsolete" not in f.description.lower():
            assert "same contents" in f.detail


def test_opencode_install_updates_on_drift(tmp_path: Path):
    """If a user hand-edits a generated file (or an older trie wrote different
    content), the next install overwrites it. Without this, a stale wrapper
    file would silently route the agent to the wrong place."""
    install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    grep_path = tmp_path / ".opencode" / "tools" / "grep.ts"
    grep_path.write_text("// stale contents from an older trie\n")

    second = install(
        target_names=["opencode"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    result = second.results[0]
    assert result.action == "updated"
    grep_file = next(f for f in result.files if f.relative_path.endswith("grep.ts"))
    assert grep_file.action == "updated"
    # Trie-generated content is back.
    body = grep_path.read_text()
    assert "Auto-generated by `trie setup" in body


