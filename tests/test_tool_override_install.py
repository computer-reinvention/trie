    install(
        target_names=["claude-code"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    body = (tmp_path / ".claude" / "hooks" / "trie-tools.json").read_text()
    assert "permissionDecision" not in body
    assert '"deny"' not in body


