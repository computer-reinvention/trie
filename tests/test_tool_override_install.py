@pytest.mark.parametrize(
    "slug",
    ["claude-desktop", "cursor", "windsurf", "vscode", "codex"],
)
def test_unsupported_harnesses_emit_needs_manual_setup(tmp_path: Path, slug: str):
    """Harnesses with no documented tool-override mechanism emit a
    `needs_manual_setup` result carrying the manual instructions, and
    write no files. The user gets honest signal that automation isn't
    possible here instead of a silent skip."""
    plan = install(
        target_names=[slug],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    result = plan.results[0]
    assert result.target == slug
    assert result.action == "needs_manual_setup"
    assert result.detail  # carries the manual_instructions text
    assert result.files == []
    # Nothing landed on disk.
    assert not (tmp_path / ".opencode").exists()
    assert not (tmp_path / ".claude").exists()


