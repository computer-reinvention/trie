def test_install_for_opencode_and_claude_code_in_one_pass(tmp_path: Path):
    """A common shape for users running both harnesses: a single
    `install(target_names=["opencode", "claude-code"], ...)` lands every
    target's files in one pass. The per-target results are independent —
    a failure on one wouldn't roll back the other."""
    plan = install(
        target_names=["opencode", "claude-code"],
        print_only=False,
        dry_run=False,
        project_root=tmp_path,
    )
    assert {r.target for r in plan.results} == {"opencode", "claude-code"}
    assert (tmp_path / ".opencode" / "tools" / "grep.ts").exists()
    assert (tmp_path / ".claude" / "hooks" / "trie-tools.json").exists()


