def _render_claude_code_hooks_json(_project_root: Path) -> str:
    """Render `.claude/hooks/trie-tools.json` — advisory hook on the built-in Grep.

    Claude Code has no tool-override surface comparable to opencode's. The
    closest mechanism is a `PreToolUse` hook that fires before every tool
    call and can emit a `systemMessage` Claude sees on its next turn. We
    use it for advisory steering only: every time Claude reaches for the
    built-in `Grep`, the hook injects a one-line tip pointing at
    `mcp__trie__grep`. Claude's call is allowed (no permissionDecision), so
    nothing breaks; we just nudge the model toward the trie tool on the
    next round.

    We don't try to intercept Read or Glob — their semantics are too
    different from trie's read/trace, and false positives on those would
    block legitimate file reads.

    The hook calls `echo` with a JSON payload on stdout. Claude Code reads
    the `systemMessage` field and shows it to the model. We keep the
    message short and instruction-shaped because system reminders are
    consumed every turn the hook fires; a long message would burn context.
    """
    # The hook file lands at `.claude/hooks/trie-tools.json`. Claude Code
    # also accepts hook configuration in settings.json, but a dedicated
    # file is easier to remove (delete the file → no more nudging) and
    # easier to detect for idempotency on re-runs of `trie setup`.
    import json as _json

    body = {
        "_comment": (
            "Auto-generated by `trie setup --override-builtins`. Do not hand-edit — "
            "re-running setup will overwrite this file. Delete it to opt out of "
            "the advisory hook."
        ),
        "hooks": {
            "PreToolUse": [
                {
                    "matcher": "Grep",
                    "hooks": [
                        {
                            "type": "command",
                            "command": (
                                'echo \'{"systemMessage":"For symbol or '
                                "code-structure queries, prefer mcp__trie__grep "
                                "(or `trie grep --json` from a shell): it "
                                "searches the indexed symbol graph and falls "
                                "back to ripgrep against in-scope source "
                                "bodies, attributing hits to enclosing "
                                "symbols. Use built-in Grep only when you "
                                "specifically need raw line-level matches.\"}'"
                            ),
                        }
                    ],
                }
            ]
        },
    }
    return _json.dumps(body, indent=2) + "\n"


