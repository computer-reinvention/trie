"""Tool-override installation: replace an agent's built-in tools with trie wrappers.

Companion to `mcp_install.py` and `hook_install.py`. Where `mcp_install` makes
trie available to an agent and `hook_install` makes it automatic, this module
makes trie *unavoidable* — it replaces or supplements the agent's built-in
tools so the agent reaches for trie reflexively, not just when prompted.

The interception story differs per harness:

- **opencode** supports drop-in tool replacement via `.opencode/tools/<name>.ts`.
  A custom tool whose filename matches a built-in name takes precedence over
  the built-in. We override `grep` (symbol-aware search) and `read`
  (triefact-first dispatch on qname vs path with a `show_source` escape
  hatch), and add `trie_trace` as a new tool for graph traversal (no
  built-in collision).
- **Claude Code** has no tool-override surface. The closest mechanism is a
  `PreToolUse` hook that fires before each built-in tool call and can emit a
  `systemMessage` Claude sees on its next turn. We use it for advisory
  steering on `Grep` only: "for symbol queries, prefer mcp__trie__grep".

Other harnesses don't have a documented interception path; they get a
`needs_manual_setup` result that explains the situation.

This is opt-in. `trie setup` prompts before writing any override files; the
user must say yes. The generated files carry the same "generated by, do not
hand-edit" notice as the hook plugin so re-running setup picks up
content drift, and the user can delete a file to opt back out.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

from trie.mcp_install import Scope

Action = Literal["created", "updated", "skipped", "preview", "error", "needs_manual_setup"]


class ToolOverrideInstallError(Exception):
    pass


@dataclass(frozen=True)
class FileToWrite:
    """One file an override target needs on disk.

    A target may need several files: e.g. opencode needs `grep.ts` and
    `read.ts` (built-in overrides) plus `trie_trace.ts` (addition). Each
    is rendered independently with its own idempotency check, so a
    partial failure on one file doesn't roll back the others.
    """

    relative_path: tuple[str, ...]
    render: Callable[[Path], str]
    description: str  # short label for the human-readable report


@dataclass(frozen=True)
class ToolOverrideApplyResult:
    """Outcome of installing override files for one target.

    `files` carries per-file results so the CLI can report which individual
    overrides landed and which were skipped. The top-level `action` summarises
    across files: if any file errored, action is "error"; if all skipped,
    "skipped"; otherwise "created"/"updated" reflecting the highest-energy
    change.
    """

    target: str
    action: Action
    files: list[ToolOverrideFileResult] = field(default_factory=list)
    detail: str = ""


@dataclass(frozen=True)
class ToolOverrideFileResult:
    """Per-file outcome inside a target's apply result."""

    relative_path: str
    action: Action
    path: Path | None
    description: str
    detail: str = ""


@dataclass(frozen=True)
class ToolOverrideTarget:
    """Static description of an agent's tool-override surface.

    `files` is the list of override files to write. Empty list means the
    target has no automatable override path; `apply_one` returns
    `needs_manual_setup` with `manual_instructions` for the user.

    `obsolete_files` is the list of paths to delete on apply if they
    exist — for cleaning up files that prior versions of `trie setup`
    wrote but newer versions no longer need (e.g. when a separate
    `trie_read.ts` tool was subsumed by an override of `read.ts`).
    The cleanup is silent: an obsolete file that doesn't exist is a
    no-op, and a successful delete is reported as part of the apply
    result so users know the migration happened.
    """

    name: str
    display_name: str
    files: tuple[FileToWrite, ...] = ()
    obsolete_files: tuple[tuple[str, ...], ...] = ()
    manual_instructions: str = ""
    # Human-readable one-line description of what installing for this target
    # actually does. Used in the interactive prompt so the user knows what
    # they're consenting to.
    summary: str = ""


